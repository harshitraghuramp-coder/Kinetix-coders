const ROOM_STORAGE_KEY = 'attendplan_custom_rooms_v1';

export function getCustomizedRooms(): Room[] {
  if (typeof window === 'undefined') return INITIAL_ROOMS;
  const raw = localStorage.getItem(ROOM_STORAGE_KEY);
  if (!raw) return INITIAL_ROOMS;
  try {
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) return parsed;
  } catch (e) {}
  return INITIAL_ROOMS;
}

export function saveCustomizedRooms(rooms: Room[]): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(ROOM_STORAGE_KEY, JSON.stringify(rooms));
}
